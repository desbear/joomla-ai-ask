export const makeT = (language) => {
  const words = WORDS[language] || (String(language).startsWith('zh') ? WORDS['zh-TW'] : WORDS['en-GB']);

  // t('key', a, b…): %s for one, %1 %2… for several
  return (key, ...args) => {
    const said = words[key] ?? WORDS['en-GB'][key] ?? key;

    if (typeof said !== 'string') {
      return said;
    }

    return args.length === 1 ? said.replace('%s', String(args[0])) : args.reduce((s, a, i) => s.replace(`%${i + 1}`, String(a)), said);
  };
};

export const zh = (language) => String(language).startsWith('zh');
