  const markdown = (text, sources) => {
    const out = [];
    let paragraph = [];
    let list = null;
    let code = null;
    let table = null;
    let quote = null;

    const endParagraph = () => {
      if (paragraph.length) {
        out.push(`<p>${paragraph.join('<br>')}</p>`);
        paragraph = [];
      }
    };
    const endList = () => {
      if (list) {
        const start = list.tag === 'ol' && list.start > 1 ? ` start="${list.start}"` : '';

        out.push(`<${list.tag}${start}>${list.items.map((item) => `<li>${item}</li>`).join('')}</${list.tag}>`);
        list = null;
      }
    };
    const endCode = () => {
      out.push(`<pre><code>${escape(code.join('\n'))}</code></pre>`);
      code = null;
    };
    const cells = (line) => line.trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map((cell) => inline(cell.trim(), sources));
    const endTable = () => {
      if (table) {
        // A separator row (|---|---|) marks the first row as the header; without one the first row is taken as the header
        const rows = table.filter((row) => !/^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$/.test(row));
        const [head, ...body] = rows.map(cells);

        if (head) {
          out.push(`<div class="mcp-ask-table"><table><thead><tr>${head.map((cell) => `<th>${cell}</th>`).join('')}</tr></thead>`
            + `<tbody>${body.map((row) => `<tr>${row.map((cell) => `<td>${cell}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`);
        }

        table = null;
      }
    };
    const endQuote = () => {
      if (quote) {
        const kind = quote.kind ? ` mcp-ask-callout mcp-ask-callout--${quote.kind}` : '';
        const label = quote.kind ? `<div class="mcp-ask-callout__label">${escape(strings[`callout${quote.kind[0].toUpperCase()}${quote.kind.slice(1)}`] || quote.label)}</div>` : '';

        out.push(`<blockquote class="mcp-ask-quote${kind}">${label}${markdown(quote.lines.join('\n'), sources)}</blockquote>`);
        quote = null;
      }
    };
    const endBlocks = () => {
      endParagraph();
      endList();
      endTable();
      endQuote();
    };

    text.split('\n').forEach((line) => {
      if (code) {
        if (line.startsWith('```')) {
          endCode();
        } else {
          code.push(line);
        }

        return;
      }

      // A callout or a quotation: "> [!TIP]" then lines starting with ">"
      const quoted = line.match(/^\s*>\s?(.*)$/);

      if (quoted) {
        if (!quote) {
          endBlocks();

          const callout = quoted[1].match(/^\[!([A-Za-z]{3,9}|\p{Script=Han}{2,3})\]\s*(.*)$/u);
          const kind = callout ? CALLOUTS[callout[1].toUpperCase()] || '' : '';

          quote = { kind, label: kind ? callout[1] : '', lines: [] };

          if (kind) {
            if (callout[2]) {
              quote.lines.push(callout[2]);
            }

            return;
          }
        }

        quote.lines.push(quoted[1]);

        return;
      }

      endQuote();

      if (/^\s*\|.*\|\s*$/.test(line)) {
        endParagraph();
        endList();
        table = table || [];
        table.push(line);

        return;
      }

      endTable();

      const heading = line.match(/^(#{1,6})\s+(.*)$/);
      const item = line.match(/^\s*(?:([-*•])|(\d+)[.)])\s+(.*)$/);
      const lone = line.match(/^\s*(!\[[^\]]{0,200}\]\([^()\s]{1,500}\))\s*$/);

      if (line.startsWith('```')) {
        endBlocks();
        code = [];
      } else if (heading) {
        endBlocks();

        const tag = heading[1].length < 3 ? 'h3' : 'h4';

        out.push(`<${tag}>${inline(heading[2], sources)}</${tag}>`);
      } else if (item) {
        const tag = item[1] ? 'ul' : 'ol';

        endParagraph();

        if (!list || list.tag !== tag) {
          endList();
          list = { tag, items: [], start: item[2] ? Number(item[2]) : 1 };
        }

        list.items.push(inline(item[3], sources));
      } else if (lone && list) {
        // The screenshot of a step belongs to that step, and the numbering goes on after it
        list.items[list.items.length - 1] += `<span class="mcp-ask-figure">${inline(lone[1], sources)}</span>`;
      } else if (list && /^\s{2,}\S/.test(line)) {
        // An indented line goes on with the item above it (a screenshot with its citation, say)
        const figure = line.match(/^\s*(!\[[^\]]{0,200}\]\([^()\s]{1,500}\))(.*)$/);

        list.items[list.items.length - 1] += figure
          ? `<span class="mcp-ask-figure">${inline(figure[1], sources)}</span>${inline(figure[2].trim(), sources)}`
          : `<br>${inline(line.trim(), sources)}`;
      } else if (lone) {
        endParagraph();
        out.push(`<p class="mcp-ask-figure">${inline(lone[1], sources)}</p>`);
      } else if (!line.trim()) {
        // A blank line ends a paragraph, but list items may be separated by one
        endParagraph();
      } else {
        endList();
        paragraph.push(inline(line, sources));
      }
    });

    if (code) {
      endCode();
    }

    endBlocks();

    return out.join('');
  };

  // ---------- Transport: POST the question, read server-sent events ----------
  // Events: status {text} · sources {items: [{title, url, section}]} · delta {text} · error {message} · done

  class AskError extends Error {}

  async function* readEvents(stream) {
    const reader = stream.pipeThrough(new TextDecoderStream()).getReader();
    let buffer = '';

    try {
      for (;;) {
        const { value, done } = await reader.read();

        if (done) {
          return;
        }

        const frames = (buffer + value).split(/\r?\n\r?\n/);

        buffer = frames.pop();

        for (const frame of frames) {
          let event = 'message';
          const data = [];

          frame.split(/\r?\n/).forEach((line) => {
            if (line.startsWith('event:')) {
              event = line.slice(6).trim();
            } else if (line.startsWith('data:')) {
              data.push(line.slice(5).trimStart());
            }
          });

          if (data.length) {
            yield { event, data: parse(data.join('\n')) };
          }
        }
      }
    } finally {
      reader.cancel().catch(() => {});
    }
  }

  // ---------- Embedded on another website ----------

  // In a frame on another website (the component's embed page): which key, which website, the
  // sign-in window. That website's page is told what to do (grow, shrink, change page, open
