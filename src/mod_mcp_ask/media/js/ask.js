        const away = new URL(href).origin !== window.location.origin;

        links.push(`<a href="${escape(href)}" rel="noopener noreferrer nofollow"${away ? ' target="_blank"' : ''}>${label}</a>`);

        return `\u0000${links.length - 1}\u0000`;
